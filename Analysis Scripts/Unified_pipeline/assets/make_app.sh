#!/bin/bash
# Build "EMT Pipeline.app": a double-clickable launcher with the EMT icon.
#
#   assets/make_app.sh            # builds <project>/EMT Pipeline.app
#
# The app runs launch_pipeline.sh from this project folder, so rebuild it if
# you move the project. You can move the app itself anywhere (Dock,
# /Applications). Output from each run goes to ~/Library/Logs/EMT_Pipeline.log.
#
# The icon comes from assets/emt_icon.png. To change it, edit emt_icon.svg and
# delete emt_icon.png; it is re-rendered here (needs the R packages from setup.sh).

set -eo pipefail

ASSETS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="$(dirname "$ASSETS")"
APP="$PROJECT/EMT Pipeline.app"

# 1. Icon: SVG -> 1024 px PNG (only when missing) -> .icns
if [ ! -f "$ASSETS/emt_icon.png" ]; then
  echo "Rendering emt_icon.svg ..."
  # run from R_reports/ so the project's renv library (which has magick) is used
  (cd "$PROJECT/R_reports" && Rscript -e "magick::image_write(magick::image_read('$ASSETS/emt_icon.svg', density = 96), '$ASSETS/emt_icon.png', format = 'png')")
fi
ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
for s in 16 32 128 256 512; do
  sips -z $s $s "$ASSETS/emt_icon.png" --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
  d=$((s * 2))
  sips -z $d $d "$ASSETS/emt_icon.png" --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$ASSETS/AppIcon.icns"
rm -rf "$(dirname "$ICONSET")"

# 2. App bundle. An AppleScript applet rather than a shell-script bundle: macOS
#    only shows the "access files in your Desktop folder" prompt to real app
#    executables, and silently blocks script bundles.
rm -rf "$APP"
APPLESCRIPT="$(mktemp -d)/emt.applescript"
cat > "$APPLESCRIPT" <<OSA
-- Generated by assets/make_app.sh; rebuild instead of editing.
on run
  set projectDir to "$PROJECT"
  set logFile to (POSIX path of (path to home folder)) & "Library/Logs/EMT_Pipeline.log"
  set launchScript to projectDir & "/launch_pipeline.sh"
  try
    do shell script "mkdir -p " & quoted form of (POSIX path of (path to home folder) & "Library/Logs") & "; echo \"=== \$(date '+%Y-%m-%d %H:%M:%S') starting EMT Pipeline ===\" >> " & quoted form of logFile
    do shell script quoted form of launchScript & " >> " & quoted form of logFile & " 2>&1 &> /dev/null &"
  on error errMsg
    display alert "EMT Pipeline did not start" message errMsg as critical
    return
  end try
  -- Give it a moment, then report if the launcher didn't come up
  repeat 20 times
    delay 0.5
    try
      do shell script "pgrep -f '[M]aster_Analysis_Launcher[.]py'"
      return
    end try
  end repeat
  set lastLines to do shell script "tail -n 6 " & quoted form of logFile
  display alert "EMT Pipeline did not start" message lastLines & return & return & "Full log: ~/Library/Logs/EMT_Pipeline.log" as warning
end run
OSA
osacompile -o "$APP" "$APPLESCRIPT"
rm -rf "$(dirname "$APPLESCRIPT")"

cp "$ASSETS/AppIcon.icns" "$APP/Contents/Resources/applet.icns"
rm -f "$APP/Contents/Resources/Assets.car"   # newer osacompile ships its icon here too
PLIST="$APP/Contents/Info.plist"
plutil -replace CFBundleIdentifier -string "local.emt-pipeline.launcher" "$PLIST"
plutil -replace CFBundleName -string "EMT Pipeline" "$PLIST"
plutil -replace CFBundleIconFile -string "applet" "$PLIST"
plutil -remove CFBundleIconName "$PLIST" 2>/dev/null || true
codesign --force --deep -s - "$APP"   # re-sign (ad hoc) after editing the bundle

touch "$APP"   # nudge Finder to pick up the icon
echo "Built: $APP"
echo "Drag it to the Dock or /Applications to start the pipeline with one click."
